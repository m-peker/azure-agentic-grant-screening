"""Write .env from the Bicep deployment outputs.

Usage: python scripts/write_env.py
Requires: az login, deployment 'main' in rg-grant-screening-dev.

Note: ARM does not preserve the casing of output names (CHAT_DEPLOYMENT comes
back as 'chaT_DEPLOYMENT'), so keys are upper-cased here.
"""
from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RG = "rg-grant-screening-dev"
AZ = shutil.which("az") or shutil.which("az.cmd")


def az(*args: str) -> str:
    return subprocess.run([AZ, *args], check=True, capture_output=True, text=True).stdout.strip()


def main() -> None:
    sub = az("account", "show", "--query", "id", "-o", "tsv")
    outputs = json.loads(az("deployment", "group", "show", "-g", RG, "-n", "main",
                            "--query", "properties.outputs", "-o", "json"))
    lines = [
        "# Generated by scripts/write_env.py from Bicep outputs. Do not commit.",
        f"AZURE_SUBSCRIPTION_ID={sub}",
        f"AZURE_RESOURCE_GROUP={RG}",
        "AZURE_LOCATION=swedencentral",
    ]
    lines += [f"{key.upper()}={val['value']}" for key, val in sorted(outputs.items())]
    (ROOT / ".env").write_text("\n".join(lines) + "\n", encoding="utf-8")
    for line in lines[1:]:
        print(line.split("=")[0])


if __name__ == "__main__":
    main()
